type Props = {
  name: IconName
  /** Pixel size; defaults to 1em so it tracks the surrounding text. */
  size?: number | string
  className?: string
  /** Provide when the icon is the only content of a control. */
  label?: string
}

export function Icon({ name, size = '1em', className, label }: Props) {
  return (
    <svg
      className={className ? `icon ${className}` : 'icon'}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      // Decorative unless it carries the control's whole meaning.
      aria-hidden={label ? undefined : true}
      role={label ? 'img' : undefined}
      aria-label={label}
      focusable="false"
    >
      {PATHS[name]}
    </svg>
  )
}
